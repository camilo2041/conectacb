const nearest = (path, p) =>
  path.reduce((best, q, i) => {
    const d = (q.lat - p.lat) ** 2 + (q.lng - p.lng) ** 2;
    return d < best.d ? { i, d } : best;
  }, { i: 0, d: Infinity }).i;

export function segment(ref) {
  const path = line(ref.line);
  const a = nearest(path, ref.from);
  const b = nearest(path, ref.to);
  return path.slice(Math.min(a, b), Math.max(a, b) + 1);
}

// Recorrido que siguen los vehículos: el trazado normal, reemplazando los tramos cerrados por su desvío.
export function servicePath(lineId) {
  let path = line(lineId);
  EVENTS.filter(e => e.closed?.line === lineId && e.detour).forEach(e => {
    const a = nearest(path, e.closed.from);
    const b = nearest(path, e.closed.to);
    path = [...path.slice(0, Math.min(a, b)), ...e.detour, ...path.slice(Math.max(a, b) + 1)];
  });
  return path;
}
